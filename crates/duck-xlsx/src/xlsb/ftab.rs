/// Nome e número de argumentos (`None` = varia).
pub type Function = (&'static str, Option<u8>);

/// A função `id`.
pub fn function(id: u16) -> Option<Function> {
    static MAP: OnceLock<Vec<Option<Function>>> = OnceLock::new();
    let map = MAP.get_or_init(|| {
        let mut v = vec![None; 485];
        for item in TABLE.split_ascii_whitespace() {
            let (id, name) = item.split_once(':').expect("número:NOME");
            let (name, args) = match name.split_once('/') {
                Some((n, a)) => (n, a.parse().ok()),
                None => (name, None),
            };
            v[id.parse::<usize>().expect("número da função")] = Some((name, args));
        }
        v
    });
    map.get(id as usize).copied().flatten()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_functions() {
        assert_eq!(function(4), Some(("SUM", None)));
        assert_eq!(function(27), Some(("ROUND", Some(2))));
        assert_eq!(function(102), Some(("VLOOKUP", None)));
        assert_eq!(function(221), Some(("TODAY", Some(0))));
        assert_eq!(function(480), Some(("IFERROR", Some(2))));
        assert_eq!(function(482), Some(("SUMIFS", None)));
        assert_eq!(function(484), Some(("AVERAGEIFS", None)));
        assert_eq!((function(255), function(9999)), (None, None));
    }
}
